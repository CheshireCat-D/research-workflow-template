"""Atomic save and editable-export checks on temporary synthetic projects."""
from __future__ import annotations

from contextlib import contextmanager
from copy import deepcopy
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

REPOSITORY = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPOSITORY))

from core import project as workflow
from core.storage import CoreError, ProjectFiles


def snapshot(root):
    result = {}
    for path in [root, *sorted(root.rglob('*'))]:
        details = path.stat()
        result[path.relative_to(root).as_posix()] = (
            path.read_bytes() if path.is_file() else None,
            details.st_mtime_ns, details.st_mode)
    return result


class StreamlinedCoreTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='rwt-streamline-')
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name) / 'synthetic project'
        workflow.initialize(self.root, 'Synthetic question')

    def registry(self):
        return json.loads((self.root / workflow.REGISTRY).read_text(encoding='utf-8'))

    def recovery(self):
        with ProjectFiles(self.root) as files:
            return workflow.recovery_view(workflow.inspect(files))

    def statement(self, identifier='S1', **updates):
        return {'id': identifier, 'text': 'Synthetic bounded claim', 'type': 'empirical',
                'scope': 'Interface testing only', **updates}

    def source(self, identifier='SRC1', **updates):
        return {'id': identifier, 'title': 'Synthetic source', 'locator': 'synthetic:source',
                'version': 'edition-1', 'content_access': 'metadata-only', **updates}

    def local(self):
        path = self.root / 'notes/data.txt'
        path.parent.mkdir(exist_ok=True)
        path.write_text('Synthetic observation\n', encoding='utf-8')
        return {'id': 'E1', 'type': 'synthetic', 'description': 'Synthetic local material',
                'provenance': 'Generated by this test',
                'location': {'kind': 'local', 'path': 'notes/data.txt'}}

    def activity(self, **updates):
        return {'id': 'A1', 'title': 'Inspect synthetic material', 'status': 'done', **updates}

    def assert_failure_without_write(self, code, action):
        before = snapshot(self.root)
        with mock.patch.object(ProjectFiles, 'write') as writer:
            with self.assertRaises(CoreError) as raised:
                action()
        self.assertEqual(raised.exception.code, code)
        writer.assert_not_called()
        self.assertEqual(snapshot(self.root), before)

    def test_batch_save_uses_one_lock_one_write_and_returns_the_committed_snapshot(self):
        evidence = self.local()
        evidence['source_ids'] = ['SRC1']
        operations = [
            {'kind': 'source', 'record': self.source()},
            {'kind': 'evidence', 'record': evidence},
            {'kind': 'activity', 'record': self.activity(inputs=['evidence:E1'])},
        ]
        events = []
        committed = False
        original_lock = ProjectFiles.lock
        original_write = ProjectFiles.write
        original_read = ProjectFiles.read

        @contextmanager
        def counted_lock(files):
            events.append('lock')
            with original_lock(files):
                yield

        def counted_write(files, relative, data):
            nonlocal committed
            events.append(relative)
            original_write(files, relative, data)
            committed = True

        def no_read_after_commit(files, relative):
            self.assertFalse(committed, 'A fallible metadata read occurred after commit')
            return original_read(files, relative)

        with mock.patch.object(ProjectFiles, 'lock', counted_lock), \
                mock.patch.object(ProjectFiles, 'write', counted_write), \
                mock.patch.object(ProjectFiles, 'read', no_read_after_commit):
            result = workflow.register_batch(self.root, operations, next_action='核对下一份材料',
                                             activity='A1', note='Synthetic interruption')
        self.assertEqual(events, ['lock', workflow.REGISTRY])
        self.assertTrue(result['registered'])
        self.assertTrue(result['checkpoint_saved'])
        self.assertFalse(result['read_only'])
        self.assertTrue(result['passed'])
        self.assertEqual(result['revision'], 4)
        self.assertEqual([row['revision'] for row in result['records']], [1, 2, 3])
        registry = self.registry()
        self.assertEqual([row['action'] for row in registry['history']],
                         ['register', 'register', 'register', 'checkpoint'])
        self.assertEqual(registry['checkpoint']['note'], 'Synthetic interruption')
        self.assertEqual(result['recovery'], self.recovery())

    def test_single_register_save_retains_the_record_version_and_final_revision(self):
        result = workflow.register(self.root, 'statement', self.statement(),
                                   next_action='Read the original source')
        self.assertEqual((result['version'], result['revision']), (1, 2))
        self.assertEqual(self.registry()['records']['statements']['S1']['version'], 1)
        self.assertEqual(result['recovery'], self.recovery())

    def test_checkpoint_report_preserves_legacy_default_result(self):
        legacy = workflow.checkpoint(self.root, 'Legacy next action')
        self.assertEqual(set(legacy), {'checkpoint_saved', 'revision', 'cursor',
                                      'scientific_validity', 'scope'})
        original = self.recovery()
        with mock.patch.object(ProjectFiles, 'read', side_effect=AssertionError('Recovery conversion read a file')), \
                mock.patch.object(ProjectFiles, 'write', side_effect=AssertionError('Recovery conversion wrote a file')):
            converted = workflow.recovery_view(original)
        self.assertEqual(converted, original)
        self.assertIsNot(converted, original)
        converted['cursor']['next_action'] = 'Only the copy changes'
        self.assertEqual(original['cursor']['next_action'], 'Legacy next action')
        result = workflow.checkpoint(self.root, 'Report next action', with_recovery=True)
        self.assertFalse(result['read_only'])
        self.assertEqual(result['recovery'], self.recovery())

    def test_invalid_checkpoint_activity_rolls_back_a_valid_batch(self):
        self.assert_failure_without_write('missing_reference', lambda: workflow.register_batch(
            self.root, [{'kind': 'statement', 'record': self.statement()}],
            next_action='Continue', activity='unknown'))

    def test_blank_next_action_and_orphan_checkpoint_options_are_rejected(self):
        for operation in (workflow.register, workflow.register_batch):
            args = ((self.root, 'statement', self.statement()) if operation is workflow.register else
                    (self.root, [{'kind': 'statement', 'record': self.statement()}]))
            for options, code in (({'next_action': '  '}, 'empty_next_action'),
                                  ({'activity': 'A1'}, 'arguments'),
                                  ({'note': 'unattached note'}, 'arguments')):
                with self.subTest(operation=operation.__name__, options=options):
                    self.assert_failure_without_write(code, lambda: operation(*args, **options))

    def test_missing_existing_local_resource_blocks_batch_and_checkpoint_commit(self):
        workflow.register(self.root, 'evidence', self.local())
        (self.root / 'notes/data.txt').unlink()
        self.assert_failure_without_write('file_missing', lambda: workflow.register_batch(
            self.root, [{'kind': 'statement', 'record': self.statement()}], next_action='Continue'))
        self.assert_failure_without_write('file_missing', lambda: workflow.checkpoint(
            self.root, 'Continue', with_recovery=True))

    def test_inspection_failure_precedes_every_combined_save_commit(self):
        operations = [
            lambda: workflow.register(self.root, 'statement', self.statement(), next_action='Continue'),
            lambda: workflow.register_batch(self.root, [{'kind': 'statement', 'record': self.statement()}],
                                             next_action='Continue'),
            lambda: workflow.checkpoint(self.root, 'Continue', with_recovery=True),
        ]
        for action in operations:
            with mock.patch.object(workflow, '_inspect_state', side_effect=CoreError('probe_failure', 'Synthetic')):
                self.assert_failure_without_write('probe_failure', action)

    def test_late_version_conflict_and_dangling_reference_do_not_commit(self):
        workflow.register(self.root, 'statement', self.statement('EXISTING'))
        failures = [
            ({'kind': 'statement', 'record': self.statement('EXISTING'),
              'replace': True, 'expected_version': 99}, 'version_conflict'),
            ({'kind': 'statement', 'record': self.statement('S2', depends_on=['MISSING'])},
             'invalid_registration'),
        ]
        for last, code in failures:
            self.assert_failure_without_write(code, lambda: workflow.register_batch(
                self.root, [{'kind': 'statement', 'record': self.statement()}, last], next_action='Continue'))

    def test_metadata_recheck_rejects_changes_before_combined_commit(self):
        original_read = ProjectFiles.read
        for target in ('project.json', workflow.REGISTRY):
            reads = 0

            def changed_read(files, relative):
                nonlocal reads
                result = original_read(files, relative)
                if relative == target:
                    reads += 1
                    if reads == 3:  # preflight load, locked load, final consistency check
                        return result + b' '
                return result

            with self.subTest(target=target), mock.patch.object(ProjectFiles, 'read', changed_read):
                self.assert_failure_without_write('concurrent_change', lambda: workflow.register_batch(
                    self.root, [{'kind': 'statement', 'record': self.statement()}], next_action='Continue'))

    def test_a_new_checkpoint_does_not_refresh_old_done_activity_bindings(self):
        workflow.register_batch(self.root, [
            {'kind': 'statement', 'record': self.statement()},
            {'kind': 'activity', 'record': self.activity(inputs=['statement:S1'])},
        ], next_action='Review', activity='A1')
        old_binding = deepcopy(self.registry()['records']['activities']['A1']['bindings'])
        result = workflow.register_batch(self.root, [
            {'kind': 'statement', 'record': self.statement(text='Revised bounded claim'),
             'replace': True, 'expected_version': 1},
        ], next_action='Reassess affected work', activity='A1')
        self.assertTrue(result['checkpoint_saved'])
        self.assertFalse(result['passed'])
        self.assertTrue(result['recovery']['needs_review'])
        self.assertEqual(result['recovery']['checkpoint']['status'], 'current')
        self.assertEqual(result['recovery']['activities'][0]['effective_status'], 'stale')
        self.assertEqual(self.registry()['records']['activities']['A1']['bindings'], old_binding)
        self.assertEqual(result['recovery'], self.recovery())
        legacy = workflow.checkpoint(self.root, 'Still requires review')
        self.assertNotIn('passed', legacy)
        report = workflow.checkpoint(self.root, 'Still requires review', with_recovery=True)
        self.assertFalse(report['passed'])

    def test_changed_local_file_is_reported_after_saving_without_rebinding_it(self):
        workflow.register(self.root, 'evidence', self.local())
        old_binding = deepcopy(self.registry()['records']['evidence']['E1']['bindings'])
        (self.root / 'notes/data.txt').write_text('Changed synthetic observation\n', encoding='utf-8')
        result = workflow.register(self.root, 'statement', self.statement(), next_action='Inspect changed data')
        self.assertTrue(result['checkpoint_saved'])
        self.assertFalse(result['passed'])
        self.assertIn('file_changed', {row['code'] for row in result['recovery']['findings']})
        self.assertEqual(self.registry()['records']['evidence']['E1']['bindings'], old_binding)

    def test_multi_edit_export_binds_versions_in_one_read_only_snapshot(self):
        workflow.register_batch(self.root, [
            {'kind': 'source', 'record': self.source()},
            {'kind': 'statement', 'record': self.statement()},
        ])
        (self.root / '.research/write.lock').unlink()
        (self.root / '.research').rmdir()
        before = snapshot(self.root)
        with mock.patch.object(ProjectFiles, 'lock', side_effect=AssertionError('Export took a writer lock')):
            exported = workflow.show(self.root, edit_refs=['statement:S1', 'source:SRC1'])
        self.assertEqual(exported, [
            {'kind': 'statement', 'record': self.statement(), 'replace': True, 'expected_version': 1},
            {'kind': 'source', 'record': self.source(), 'replace': True, 'expected_version': 1},
        ])
        self.assertEqual(snapshot(self.root), before)
        exported[0]['record']['text'] = 'A user correction'
        result = workflow.register_batch(self.root, exported, next_action='Review the correction')
        self.assertEqual([row['version'] for row in result['records']], [2, 2])

    def test_edit_export_keeps_its_original_expected_version_after_another_update(self):
        workflow.register(self.root, 'statement', self.statement())
        exported = workflow.show(self.root, edit_refs=['statement:S1'])
        workflow.register(self.root, 'statement', self.statement(text='Other edit'),
                          replace=True, expected_version=1)
        self.assert_failure_without_write('version_conflict', lambda: workflow.register_batch(
            self.root, exported, next_action='Continue'))

    def test_edit_export_arguments_missing_references_and_concurrent_changes_are_read_only(self):
        workflow.register(self.root, 'statement', self.statement())
        invalid = [[], ['statement:S1', 'statement:S1'], ['S1'], ['unknown:S1'], [1], 'statement:S1']
        for references in invalid:
            self.assert_failure_without_write('arguments', lambda: workflow.show(self.root, edit_refs=references))
        for options in ({'kind': 'statement'}, {'identifier': 'S1'}, {'data_only': True}):
            self.assert_failure_without_write('arguments', lambda: workflow.show(
                self.root, edit_refs=['statement:S1'], **options))
        self.assert_failure_without_write('missing_reference', lambda: workflow.show(
            self.root, edit_refs=['statement:S1', 'source:absent']))
        original_read = ProjectFiles.read
        reads = 0

        def changed_read(files, relative):
            nonlocal reads
            result = original_read(files, relative)
            if relative == workflow.REGISTRY:
                reads += 1
                if reads == 2:
                    return result + b' '
            return result

        with mock.patch.object(ProjectFiles, 'read', changed_read):
            self.assert_failure_without_write('concurrent_change', lambda: workflow.show(
                self.root, edit_refs=['statement:S1']))

    def test_default_show_and_data_only_keep_their_existing_shapes(self):
        original = self.statement()
        registered = workflow.register(self.root, 'statement', original)
        self.assertEqual(set(registered), {'registered', 'kind', 'id', 'version', 'revision',
                                           'scientific_validity', 'scope'})
        batch = workflow.register_batch(self.root, [{'kind': 'source', 'record': self.source()}])
        self.assertEqual(set(batch), {'registered', 'registered_count', 'records', 'revision',
                                     'scientific_validity', 'scope'})
        before = snapshot(self.root)
        full = workflow.show(self.root, kind='statement', identifier='S1')
        self.assertEqual(full['envelope']['data'], original)
        self.assertEqual(full['envelope']['version'], 1)
        self.assertTrue(full['read_only'])
        self.assertEqual(workflow.show(self.root, kind='statement')['records'], [{'id': 'S1', 'version': 1}])
        self.assertEqual(workflow.show(self.root, kind='statement', identifier='S1', data_only=True), original)
        self.assertEqual(snapshot(self.root), before)



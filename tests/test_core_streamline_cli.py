"""Real CLI journeys for shorter project save, edit and recovery operations."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tests'))
from replay_support import reviewed_resource


class StreamlinedCLI(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='rwt-streamline-cli-')
        self.addCleanup(temporary.cleanup)
        self.base = Path(temporary.name)
        self.project = self.base / 'project with spaces'
        self.script = ROOT / 'tools/research.py'
        self.run_cli('init', '--output', self.project, '--title', '可恢复的问题', cwd=self.base)

    def run_cli(self, *args, expected=0, payload=None, cwd=None, markdown=False):
        process = subprocess.run([sys.executable, '-I', '-B', str(self.script), *map(str, args)],
                                 cwd=cwd or self.project, capture_output=True, text=True,
                                 encoding='utf-8', timeout=30,
                                 input=json.dumps(payload, ensure_ascii=False) if payload is not None else None)
        self.assertEqual(process.returncode, expected, process.stdout + process.stderr)
        return process.stdout if markdown else json.loads(process.stdout)

    def seed(self):
        (self.project / 'input.txt').write_text('original observation\n', encoding='utf-8')
        evidence = {'id': 'E1', 'type': 'synthetic', 'description': 'Test observation',
                    'provenance': 'Generated by this interface test',
                    'location': {'kind': 'local', 'path': 'input.txt'}}
        activity = {'id': 'A1', 'title': 'Review observation', 'status': 'done',
                    'inputs': ['evidence:E1']}
        return self.run_cli('register-batch', '--file', '-', '--next-action', '核对下一份材料',
                            '--activity', 'A1', payload=[{'kind': 'evidence', 'record': evidence},
                                                       {'kind': 'activity', 'record': activity}])

    def test_one_export_one_save_and_one_later_recovery(self):
        saved = self.seed()
        self.assertTrue(saved['registered'] and saved['checkpoint_saved'] and saved['passed'])
        self.assertEqual(saved['recovery']['next_action'], '核对下一份材料')
        (self.project / 'input.txt').write_text('reviewed replacement observation\n', encoding='utf-8')
        batch = self.run_cli('show', '--edit', 'evidence:E1', 'activity:A1')
        self.assertEqual([item['expected_version'] for item in batch], [1, 1])
        self.assertTrue(all(item['replace'] for item in batch))
        batch[1]['record']['note'] = 'Replacement observation actually reviewed in this test.'
        saved = self.run_cli('register-batch', '--file', '-', '--next-action', '完成有界复核',
                             '--activity', 'A1', payload=batch)
        self.assertTrue(saved['passed'])
        self.assertEqual(saved['revision'], 6)
        recovered = self.run_cli('resume')
        self.assertEqual(recovered, saved['recovery'])
        report = self.run_cli('resume', '--format', 'markdown', markdown=True)
        self.assertIn('完成有界复核', report)
        self.assertIn('Checkpoint status: current', report)

    def test_exit_one_reports_saved_state_without_refreshing_old_done_work(self):
        self.seed()
        (self.project / 'input.txt').write_text('changed after review\n', encoding='utf-8')
        batch = self.run_cli('show', '--edit', 'evidence:E1')
        saved = self.run_cli('register-batch', '--file', '-', '--next-action', '先重新审阅活动',
                             payload=batch, expected=1)
        self.assertTrue(saved['registered'] and saved['checkpoint_saved'])
        self.assertFalse(saved['passed'])
        self.assertTrue(saved['recovery']['needs_review'])
        self.assertEqual(saved['recovery']['activities'][0]['effective_status'], 'stale')
        reported = self.run_cli('checkpoint', '--next-action', '仍需重新审阅', '--report', expected=1)
        self.assertTrue(reported['checkpoint_saved'])
        self.assertTrue(reported['recovery']['needs_review'])

    def test_exported_versions_conflict_instead_of_overwriting_a_newer_record(self):
        self.seed()
        batch = self.run_cli('show', '--edit', 'evidence:E1', 'activity:A1')
        self.run_cli('register-batch', '--file', '-', payload=batch)
        before = (self.project / 'records/registry.json').read_bytes()
        failure = self.run_cli('register-batch', '--file', '-', '--next-action', 'Do not overwrite',
                               payload=batch, expected=2)
        self.assertFalse(failure['passed'])
        self.assertEqual((self.project / 'records/registry.json').read_bytes(), before)

    def test_repeated_edit_flags_keep_all_references_and_reject_duplicates(self):
        self.seed()
        together = self.run_cli('show', '--edit', 'evidence:E1', 'activity:A1')
        repeated = self.run_cli('show', '--edit', 'evidence:E1', '--edit', 'activity:A1')
        self.assertEqual(repeated, together)
        before = (self.project / 'records/registry.json').read_bytes()
        self.run_cli('show', '--edit', 'evidence:E1', '--edit', 'evidence:E1', expected=2)
        self.assertEqual((self.project / 'records/registry.json').read_bytes(), before)

    def test_current_directory_only_does_not_search_parents_or_initialize(self):
        nested = self.project / 'notes'; nested.mkdir()
        before = set(nested.iterdir())
        result = self.run_cli('resume', cwd=nested, expected=2)
        self.assertFalse(result['passed'])
        self.assertEqual(set(nested.iterdir()), before)
        restored = self.run_cli('resume', '--root', '..', cwd=nested)
        self.assertTrue(restored['passed'])

    def test_invalid_option_combinations_do_not_write_registry(self):
        self.seed()
        before = (self.project / 'records/registry.json').read_bytes()
        for args in [('show', '--edit', 'evidence:E1', '--kind', 'evidence'),
                     ('show', '--edit'),
                     ('register-batch', '--file', '-', '--note', 'Missing next action')]:
            self.run_cli(*args, payload=[] if args[0] == 'register-batch' else None, expected=2)
            self.assertEqual((self.project / 'records/registry.json').read_bytes(), before)

    def test_preserved_resource_versions_remain_hash_bound(self):
        history = json.loads((ROOT / 'evals/current/guidance-history.json').read_text(encoding='utf-8'))
        for name in ('core/project.py', 'core/cli.py', 'core/skill-bridge.md'):
            resource = history['resources'][name]
            for version in [resource, *resource.get('versions', [])]:
                data = reviewed_resource(name, version['sha256'])
                self.assertEqual(hashlib.sha256(data).hexdigest(), version['sha256'])


if __name__ == '__main__':
    unittest.main()
